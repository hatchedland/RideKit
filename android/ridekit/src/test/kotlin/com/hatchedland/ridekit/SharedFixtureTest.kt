    fun appVersion() = tests("app-version") { input, expected ->
        assertEquals(expected.jsonPrimitive.boolean, AppVersion.needsUpdate(input.str("current"), input.opt("minimum")?.jsonPrimitive?.content))
    }

    @TestFactory
    fun trackCodec(): List<DynamicTest> = listOf(
        DynamicTest.dynamicTest("track-v2.bin decodes to track-v2.json") {
            val points = TrackCodec.decode(File(dir, "track-v2.bin").readBytes())
            val expected = Json.parseToJsonElement(File(dir, "track-v2.json").readText()).jsonObject.arr("points").map { it.jsonObject }
            assertEquals(expected.size, points.size)
            expected.zip(points).forEach { (e, p) ->
                fun f32(v: Double?) = v?.toFloat()?.toDouble()
                assertEquals(e.num("t"), p.t)
                assertEquals(e.num("lat"), p.coordinate.latitude)
                assertEquals(e.num("lon"), p.coordinate.longitude)
                assertEquals(f32(e.optNum("alt")), p.altitude)
                assertEquals(f32(e.optNum("speed")), p.speed)
                assertEquals(f32(e.optNum("course")), p.course)
                assertEquals(f32(e.num("hAcc")), p.horizontalAccuracy)
                assertEquals(f32(e.optNum("lean")), p.lean)
            }
        },
        DynamicTest.dynamicTest("track round-trips, empty included") {
            val points = TrackCodec.decode(File(dir, "track-v2.bin").readBytes())
            assertEquals(points, TrackCodec.decode(TrackCodec.encode(points)))
            assertEquals(emptyList<TrackPoint>(), TrackCodec.decode(TrackCodec.encode(emptyList())))
        },
        DynamicTest.dynamicTest("old LZFSE tracks are refused clearly") {
            val error = runCatching { TrackCodec.decode(byteArrayOf(0x62, 0x76, 0x78, 0x32, 0, 0, 0, 0)) }.exceptionOrNull()
            assertEquals(TrackCodec.DecodeException.Reason.LEGACY, (error as TrackCodec.DecodeException).reason)
        },
    )
}
