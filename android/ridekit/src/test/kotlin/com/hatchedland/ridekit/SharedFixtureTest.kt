/**
 * The golden files in spec/fixtures, generated by the Swift RideKit: the Kotlin port must produce the
 * same results (tolerances: spec/fixtures/README.md).
 */
class SharedFixtureTest {

    private val dir = File(System.getProperty("fixtures") ?: "../../spec/fixtures")

    private fun cases(name: String): List<JsonObject> =
        Json.parseToJsonElement(File(dir, "$name.json").readText()).jsonObject["cases"]!!.jsonArray.map { it.jsonObject }

    private fun tests(name: String, check: (input: JsonObject, expected: JsonElement) -> Unit): List<DynamicTest> =
        cases(name).map { c ->
            DynamicTest.dynamicTest("$name: ${c.str("name")}") { check(c["input"]!!.jsonObject, c["expected"]!!) }
        }

    // MARK: JSON helpers ("a missing key means null")

    private fun JsonObject.opt(key: String): JsonElement? = this[key]?.takeUnless { it is JsonNull }
    private fun JsonObject.str(key: String) = this[key]!!.jsonPrimitive.content
    private fun JsonObject.num(key: String) = this[key]!!.jsonPrimitive.double
    private fun JsonObject.optNum(key: String) = opt(key)?.jsonPrimitive?.double
    private fun JsonObject.arr(key: String) = this[key]?.jsonArray ?: JsonArray(emptyList())
    private fun JsonElement.latLon() = jsonObject.let { Coordinate(it.num("lat"), it.num("lon")) }
    private fun JsonObject.optLatLon(key: String) = opt(key)?.latLon()
    private fun JsonArray.strings() = map { it.jsonPrimitive.content }

    private fun JsonElement.point(): TrackPoint = jsonArray.let { a ->
        fun opt(i: Int) = a[i].takeUnless { it is JsonNull }?.jsonPrimitive?.double
        TrackPoint(a[0].jsonPrimitive.double, Coordinate(a[1].jsonPrimitive.double, a[2].jsonPrimitive.double),
            opt(3), opt(4), opt(5), a[6].jsonPrimitive.double, opt(7))
    }
    private fun JsonObject.track(key: String = "track") = arr(key).map { it.point() }

    private fun privacy(input: JsonObject) = SharePrivacy(
        input.arr("zones").mapIndexed { i, z ->
            PrivacyZone("z$i", "z", z.jsonObject["center"]!!.latLon(), z.jsonObject.num("radius"))
        },
        input.num("endTrim"),
    )

    private fun near(expected: Double?, actual: Double?, tolerance: Double, what: String) {
        if (expected == null || actual == null) return assertEquals(expected, actual, what)
        assertTrue(abs(expected - actual) <= tolerance, "$what: expected $expected, got $actual")
    }

    // MARK: Fixtures

    @TestFactory
    fun sharePrivacy() = tests("share-privacy") { input, expected ->
        val p = privacy(input)
        val track = input.track()
        val kept = p.redact(track)
        assertEquals(expected.jsonObject.arr("visible").map { it.jsonPrimitive.int }, kept.map { track.indexOf(it) })
        assertEquals(expected.jsonObject.arr("shows").map { it.jsonPrimitive.boolean }, input.arr("probes").map { p.shows(it.latLon(), track) })
    }

    @TestFactory
    fun sharedRideRedaction() = tests("shared-ride-redaction") { input, expected ->
        val (stops, photos) = redact(
            privacy(input), input.track(),
            input.arr("stops").map { SharedStop(it.jsonObject.str("id"), it.jsonObject["at"]!!.latLon(), it.jsonObject.arr("photoIDs").strings()) },
            input.arr("photos").map { SharedPhoto(it.jsonObject.str("id"), it.jsonObject.optLatLon("at")) },
        )
        assertEquals(expected.jsonObject.arr("stops").strings(), stops.map { it.id })
        assertEquals(
            expected.jsonObject.arr("photos").map { it.jsonObject.str("id") to it.jsonObject.optLatLon("at") },
            photos.map { it.id to it.coordinate },
        )
    }

    @TestFactory
    fun wishlist() = tests("wishlist") { input, expected ->
        val refs = input.arr("wishlist").map { SpotReference(it.jsonObject.str("id"), it.jsonObject["at"]!!.latLon()) }
        val media = input.arr("media").map { MediaCandidate(it.jsonObject.str("id"), it.jsonObject.num("t"), it.jsonObject.optLatLon("at")) }
        val e = expected.jsonObject

        val visits = WishlistMatcher.visits(refs, input.track(), media)
        val expectedVisits = e.arr("visits").map { it.jsonObject }
        assertEquals(expectedVisits.size, visits.size, "visits")
        expectedVisits.zip(visits).forEach { (ev, v) ->
            assertEquals(ev.str("spotID"), v.spotID)
            near(ev.num("t"), v.t, 0.001, "visit time")
            when (val evidence = v.evidence) {
                is WishlistMatcher.Evidence.Stopped -> assertEquals("stopped", ev.str("evidence"))
                is WishlistMatcher.Evidence.Photo -> {
                    assertEquals("photo", ev.str("evidence"))
                    assertEquals(ev.str("mediaID"), evidence.mediaID)
                }
            }
        }

        val nearby = WishlistMatcher.nearbyAlerts(input["position"]!!.latLon(), refs, input.arr("alreadyAlerted").strings().toSet())
        val expectedNearby = e.arr("nearby").map { it.jsonObject }
        assertEquals(expectedNearby.map { it.str("spotID") }, nearby.map { it.first.id })
        expectedNearby.zip(nearby).forEach { (en, n) -> near(en.num("distance"), n.second, 0.01, "nearby distance") }

        val revisit = input.arr("revisitProbes").map { RevisitDetector.existingSpot(it.latLon(), refs)?.id }
        assertEquals(e.arr("revisit").map { if (it is JsonNull) null else it.jsonPrimitive.content }, revisit)
    }

    @TestFactory
    fun rideTimePlan() = tests("ride-time-plan") { input, expected ->
        val pace = RidePace.learn(input.arr("rides").map {
            val r = it.jsonObject
            RidePace.Sample(r.num("distance"), r.num("moving"), r.num("elapsed"))
        })
        val plan = RideTimePlan(input.num("departure"), input.num("distance"), input.num("roadSeconds"), input["destination"]!!.latLon(), pace)
        val e = expected.jsonObject
        near(e.optNum("paceSpeed"), pace.movingSpeedMps, 1e-9, "pace speed")
        near(e.num("stopShare"), pace.stopShare, 1e-9, "stop share")
        assertEquals(e["rideCount"]!!.jsonPrimitive.int, pace.rideCount)
        near(e.num("movingSeconds"), plan.movingSeconds, 0.001, "moving")
        near(e.num("breakSeconds"), plan.breakSeconds, 0.001, "breaks")
        near(e.num("arrival"), plan.arrival, 0.001, "arrival")
        near(e.optNum("sunset"), plan.sunset, 1.0, "sunset")
        near(e.optNum("latestDeparture"), plan.latestDeparture, 1.0, "leave by")
        assertEquals(e["arrivesAfterDark"]!!.jsonPrimitive.boolean, plan.arrivesAfterDark)
        assertEquals(e["canStillArriveInDaylight"]!!.jsonPrimitive.boolean, plan.canStillArriveInDaylight)
    }

    @TestFactory
    fun weatherAlerts() = tests("weather-alerts") { input, expected ->
        val forecast = input.arr("forecast").map {
            val h = it.jsonObject
            WeatherHour(h.num("start"), h.str("condition"), feelsLike = h.optNum("feelsLike"),
                rainChance = h["rainChance"]!!.jsonPrimitive.int, thunderChance = h["thunderChance"]!!.jsonPrimitive.int,
                gustKmh = h.optNum("gustKmh"))
        }
        val state = WeatherAlertState()
        val steps = input.arr("steps").map { it.jsonObject }
        val alerts = steps.map { step ->
            if (step.str("call") == "sunset") WeatherAlerts.sunset(step.optNum("sunset"), step.num("now"), step.optNum("remaining"), state)
            else WeatherAlerts.next(forecast, step.num("now"), state)
        }
        val outlook = steps.firstOrNull()?.let { WeatherAlerts.outlook(forecast, it.num("now")) }

        fun check(e: JsonElement?, a: WeatherAlert?, what: String) {
            if (e == null || e is JsonNull) return assertEquals(null, a, what)
            val o = e.jsonObject
            assertEquals(o.str("kind"), a?.kind?.raw, what)
            near(o.optNum("at"), a?.at, 0.001, "$what at")
            assertEquals(o.opt("percent")?.jsonPrimitive?.int, a?.percent, "$what percent")
            near(o.optNum("value"), a?.value, 1e-9, "$what value")
        }
        val e = expected.jsonObject
        e.arr("alerts").forEachIndexed { i, a -> check(a, alerts[i], "step $i") }
        assertEquals(e.arr("alerts").size, alerts.size)
        check(e.opt("outlook"), outlook, "outlook")
    }

    @TestFactory
    fun famousPlaces() = tests("famous-places") { input, expected ->
        val candidates = input.arr("candidates").map {
            val p = it.jsonObject
            Place(p.str("name"), p["at"]!!.latLon(), id = p.opt("id")?.jsonPrimitive?.content,
                rating = p.optNum("rating"), ratingCount = p.opt("ratingCount")?.jsonPrimitive?.int)
        }
        val position = input["position"]!!.latLon()
        val ahead = FamousPlaces.ahead(position, input.optNum("course"), candidates, input.arr("alreadyAnnounced").strings().toSet(),
            input.arr("savedSpots").map { it.latLon() })
        val e = expected.jsonObject
        val expectedAhead = e.arr("ahead").map { it.jsonObject }
        assertEquals(expectedAhead.map { it.str("key") }, ahead.map { FamousPlaces.key(it.first) })
        expectedAhead.zip(ahead).forEach { (ea, a) -> near(ea.num("distance"), a.second, 0.01, "distance") }
        near(e.optNum("heading"), FamousPlaces.heading(input.track("recentTrack")), 0.0001, "heading")
        assertEquals(e["needsSearch"]!!.jsonPrimitive.boolean, FamousPlaces.needsSearch(position, input.optLatLon("lastSearch")))
    }

    @TestFactory
    fun trail() = tests("trail") { input, expected ->
        val trail = Trail.build(
            input.num("rideStart"), input.num("rideEnd"), input.track(),
            input.arr("media").map { val m = it.jsonObject; Trail.Media(m.str("id"), m.num("t"), m.optLatLon("at"), m.opt("spotID")?.jsonPrimitive?.content) },
            input.arr("spots").map { val s = it.jsonObject; Trail.Spot(s.str("id"), s["at"]!!.latLon(), s.num("markedAt")) },
            input.arr("songs").map { val s = it.jsonObject; Trail.Song(s.str("id"), s.num("t")) },
        )
        val e = expected.jsonObject
        val stops = e.arr("stops").map { it.jsonObject }
        assertEquals(stops.map { it.str("id") }, trail.stops.map { it.id })
        stops.zip(trail.stops).forEach { (es, s) ->
            assertEquals(es.str("kind"), if (s.kind is Trail.Stop.Kind.Spot) "spot" else "cluster")
            assertEquals(es["at"]!!.latLon(), s.coordinate)
            near(es.num("arrivedAt"), s.arrivedAt, 0.001, "arrived")
            near(es.num("departedAt"), s.departedAt, 0.001, "departed")
            near(es.optNum("distanceFromStart"), s.distanceFromStart, 0.01, "km from start")
            assertEquals(es.arr("mediaIDs").strings(), s.mediaIDs)
            assertEquals(es.arr("songIDs").strings(), s.songIDs)
        }
        val legs = e.arr("legs").map { it.jsonObject }
        assertEquals(legs.size, trail.legs.size)
        legs.zip(trail.legs).forEach { (el, l) ->
            near(el.num("start"), l.start, 0.001, "leg start")
            near(el.num("end"), l.end, 0.001, "leg end")
            near(el.optNum("distance"), l.distance, 0.01, "leg distance")
            assertEquals(el.arr("mediaIDs").strings(), l.mediaIDs)
            assertEquals(el.arr("songIDs").strings(), l.songIDs)
        }
    }

    @TestFactory
    fun rideNaming() = tests("ride-naming") { input, expected ->
        val e = expected.jsonObject
        if (input.str("call") == "suggest") {
            val suggestions = RideNaming.suggestions(input.str("input"), input.arr("recentRideNames").strings(), input.arr("wishlistSpotNames").strings())
            assertEquals(e.arr("suggestions").strings(), suggestions)
        } else {
            // The app's job on Android (ICU); java.time gives the same CLDR pattern on the JVM.
            val locale = Locale.forLanguageTag(input.str("locale").replace('_', '-'))
            val date = DateTimeFormatter.ofLocalizedPattern("yMMMd").withLocale(locale)
                .format(Instant.ofEpochMilli((input.num("startedAt") * 1000).toLong()).atZone(ZoneId.of(input.str("timeZone"))))
            assertEquals(e.str("name"), RideNaming.resolve(input.str("input"), date, input.arr("existingNames").strings()))
        }
    }

